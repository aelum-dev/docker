#!/usr/bin/env bash
#
# build-release-metadata.sh — turn a signed ISO into the two artifacts the
# automated release pipeline needs:
#
#   1. latest.json   — machine-readable metadata, uploaded to the R2 bucket
#                      and served publicly at /latest.json (public R2 bucket).
#   2. release.ts    — the website's generated release module (committed to the
#                      website repo so the deployed site stays fully offline).
#
# Both are derived from the SAME source of truth (the ISO + its checksums + the
# signing key), so the website links and the R2 assets can never drift apart.
#
# Usage:
#   scripts/build-release-metadata.sh \
#       --iso output/aelum-2026.08.28-x86_64.iso \
#       --tag v2026.08.28 \
#       --bucket aelum \
#       --public-base https://aelum.gitlab.io \
#       --signing-uid "Ivan Kornienko <ik.workmail39@gmail.com>" \
#       --signing-fp "A675F61C22C26FCE187262E448CC48FDFD881E0D" \
#       --expires 2029-08-27 \
#       --out-dir /tmp/release
#
# Writes:  $out-dir/latest.json   and   $out-dir/release.ts
#
# The asset URLs are built from --public-base + tag + filename. Point
# --public-base at your Cloudflare CDN domain (or the R2 bucket endpoint) so the
# links resolve to the published files.

set -euo pipefail

ISO=""
TAG=""
BUCKET="${R2_BUCKET:-aelum}"
PUBLIC_BASE="${R2_PUBLIC_BASE:-https://${BUCKET}.r2.cloudflarestorage.com}"
SIGNING_UID=""
SIGNING_FP=""
SIGNING_FP_TOP=""
SIGNING_FP_BOT=""
EXPIRES=""
OUT_DIR="$(mktemp -d)"  # default; --out-dir overrides this below

usage() { sed -n '2,30p' "$0" | sed 's/^# \{0,1\}//'; exit 1; }

while [[ $# -gt 0 ]]; do
  case "$1" in
    --iso)         ISO="$2"; shift 2 ;;
    --tag)         TAG="$2"; shift 2 ;;
    --bucket)      BUCKET="$2"; shift 2 ;;
    --public-base) PUBLIC_BASE="$2"; shift 2 ;;
    --signing-uid) SIGNING_UID="$2"; shift 2 ;;
    --signing-fp)  SIGNING_FP="$2"; shift 2 ;;
    --signing-fp-top) SIGNING_FP_TOP="$2"; shift 2 ;;
    --signing-fp-bot) SIGNING_FP_BOT="$2"; shift 2 ;;
    --expires)     EXPIRES="$2"; shift 2 ;;
    --out-dir)     OUT_DIR="$2"; shift 2 ;;
    -h|--help)     usage ;;
    *) echo "Unknown option: $1" >&2; usage ;;
  esac
done

if [[ -z "$ISO" || -z "$TAG" ]]; then
  echo "Error: --iso and --tag are required." >&2
  exit 1
fi
ISO="$(realpath "$ISO")"
BASE="$(basename "$ISO")"
mkdir -p "$OUT_DIR"

# ── checksums / size ──────────────────────────────────────────────────────────
SHA256="$(sha256sum "$ISO" | awk '{print $1}')"
SHA512="$(sha512sum "$ISO" | awk '{print $1}')"
SIZE_BYTES="$(stat -c %s "$ISO")"

# Derive version + arch from the filename (aelum-<version>-<arch>.iso).
VERSION="${BASE#aelum-}"; VERSION="${VERSION%-x86_64.iso}"
ARCH="${BASE##*-}"; ARCH="${ARCH%.iso}"

# Normalise the public base (strip trailing slash) and build asset URLs.
PUBLIC_BASE="${PUBLIC_BASE%/}"
iso_url="${PUBLIC_BASE}/${TAG}/${BASE}"
json_url="${PUBLIC_BASE}/${TAG}/${BASE}.sha256" # placeholder key; real URLs below

# ── latest.json ───────────────────────────────────────────────────────────────
cat > "$OUT_DIR/latest.json" <<JSON
{
  "tag": "${TAG}",
  "version": "${VERSION}",
  "arch": "${ARCH}",
  "filename": "${BASE}",
  "publishedAt": "$(date -u +%Y-%m-%dT%H:%M:%SZ)",
  "sizeBytes": ${SIZE_BYTES},
  "sha256": "${SHA256}",
  "sha512": "${SHA512}",
  "urls": {
    "iso": "${iso_url}",
    "sha256": "${PUBLIC_BASE}/${TAG}/${BASE}.sha256",
    "sha512": "${PUBLIC_BASE}/${TAG}/${BASE}.sha512",
    "signature": "${PUBLIC_BASE}/${TAG}/${BASE}.asc",
    "key": "${PUBLIC_BASE}/${TAG}/aelum-release-key.asc"
  },
  "signingKey": {
    "uid": "${SIGNING_UID}",
    "fingerprint": "${SIGNING_FP}",
    "fingerprintTop": "${SIGNING_FP_TOP}",
    "fingerprintBot": "${SIGNING_FP_BOT}",
    "expires": "${EXPIRES}"
  }
}
JSON

# ── release.ts (website module) ───────────────────────────────────────────────
# Written as a TS module the Download section imports. Escaped so embedded
# quotes/newlines survive.
esc() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }

cat > "$OUT_DIR/release.ts" <<'TS'
/* eslint-disable */
// AUTO-GENERATED by docker/scripts/build-release-metadata.sh — do not edit by hand.
// Regenerated on every release commit. See website/scripts/fetch-release.mjs.
import type { ReleaseMetadata } from "./release-type";

export const release: ReleaseMetadata = {
TS
{
  echo "  tag: \"$(esc "$TAG")\","
  echo "  version: \"$(esc "$VERSION")\","
  echo "  arch: \"$(esc "$ARCH")\","
  echo "  filename: \"$(esc "$BASE")\","
  echo "  publishedAt: \"$(esc "$(date -u +%Y-%m-%dT%H:%M:%SZ)")\","
  echo "  sizeBytes: ${SIZE_BYTES},"
  echo "  sha256: \"$(esc "$SHA256")\","
  echo "  sha512: \"$(esc "$SHA512")\","
  echo "  urls: {"
  echo "    iso: \"$(esc "$iso_url")\","
  echo "    sha256: \"${PUBLIC_BASE}/${TAG}/${BASE}.sha256\","
  echo "    sha512: \"${PUBLIC_BASE}/${TAG}/${BASE}.sha512\","
  echo "    signature: \"${PUBLIC_BASE}/${TAG}/${BASE}.asc\","
  echo "    key: \"${PUBLIC_BASE}/${TAG}/aelum-release-key.asc\""
  echo "  },"
  echo "  signingKey: {"
  echo "    uid: \"$(esc "$SIGNING_UID")\","
  echo "    fingerprint: \"$(esc "$SIGNING_FP")\","
  echo "    fingerprintTop: \"$(esc "$SIGNING_FP_TOP")\","
  echo "    fingerprintBot: \"$(esc "$SIGNING_FP_BOT")\","
  echo "    expires: \"$(esc "$EXPIRES")\""
  echo "  }"
  echo "};"
} >> "$OUT_DIR/release.ts"
echo "" >> "$OUT_DIR/release.ts"

echo "==> Wrote $OUT_DIR/latest.json"
echo "==> Wrote $OUT_DIR/release.ts"
echo
echo "latest.json:"
cat "$OUT_DIR/latest.json"
