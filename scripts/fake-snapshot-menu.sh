#!/usr/bin/env bash
set -uo pipefail

# fake-snapshot-menu.sh — run the boot-menu generator against a fixture, on the
# host, with no disk and no root.
#
#   ./scripts/fake-snapshot-menu.sh          # extract the generator and run it
#   GEN=/tmp/gen.sh ./scripts/fake-snapshot-menu.sh   # run a script you already have
#
# What exists here is a fake ESP (with this install's own menu entry to copy
# options from), a fake snapper config, a fake snapshot store, and a stub
# findmnt that answers the three questions the generator asks. Everything it
# reads and writes is under one temporary directory.
#
# This is not the installer's test suite: those check the text of the generator.
# This one runs it as shell, which is the only way to catch a fragment that is
# malformed, a title that lost its date, or a run that leaves the file behind
# when the snapshots are gone. It does not touch the real mount table, and it
# says so: a real boot is checked by make -C docker test-one / menu-shots.

PROFILE_DIR="$(cd "$(dirname "$0")/.." && pwd)"
GEN="${GEN:-$PROFILE_DIR/logs/snapshot-menu/aelum-refind-snapshots.sh}"
KEEP="${KEEP:-0}"

fails=0
ok()   { echo "  ok   - $*"; }
bad()  { echo "  FAIL - $*"; fails=$((fails + 1)); }
check() { # check <description> <command...>
    local desc=$1; shift
    if "$@" >/dev/null 2>&1; then ok "$desc"; else bad "$desc  [$*]"; fi
}
absent() { # absent <description> <pattern> <file>
    local desc=$1 pat=$2 file=$3
    if LC_ALL=C grep -qE "$pat" "$file" 2>/dev/null; then bad "$desc"; else ok "$desc"; fi
}
count() { local n; n=$(grep -cE "$1" "$2" 2>/dev/null); echo "${n:-0}"; }

if [ ! -x "$GEN" ]; then
    echo "extracting the generator from the installer source ..."
    OUT="$GEN" "$PROFILE_DIR/scripts/extract-snapshot-generator.sh" || exit 1
fi
[ -r "$GEN" ] || { echo "no generator to run: $GEN" >&2; exit 1; }

# The generator looks for an ESP at /efi and /boot before it asks findmnt. If
# this host really has one, the fixture would not be the one it writes to.
for candidate in /efi /boot; do
    if [ -d "$candidate/EFI/refind/aelum" ]; then
        echo "this host has $candidate/EFI/refind/aelum; the fixture would not be used" >&2
        exit 1
    fi
done

FAKE=$(mktemp -d /tmp/aelum-fake-snapshot-menu.XXXXXX)
[ "$KEEP" = 1 ] || trap 'rm -rf "$FAKE"' EXIT
BIN="$FAKE/bin"
ID=3f5b5703
UUID=3f5b5703-93af-49ca-8fbb-9d93703a72c8
ESP="$FAKE/efi"
FRAGMENT="$ESP/EFI/refind/aelum/$ID-snapshots.conf"

mkdir -p "$BIN" "$ESP/EFI/refind/aelum" "$FAKE/etc/snapper/configs"

# Stub findmnt: the three lookups the generator makes, in the spelling the real
# findmnt uses (a btrfs subvolume mount is reported as /dev/vda2[/@]).
cat >"$BIN/findmnt" <<EOF
#!/bin/sh
case "\$*" in
    *"TARGET -t vfat"*) echo "$ESP" ;;
    *"no UUID"*)        echo "$UUID" ;;
    *"no SOURCE"*)      echo "/dev/vda2[@]" ;;
    *)                 exit 0 ;;
esac
EOF
chmod +x "$BIN/findmnt"

# This install's own menu entry: the generator copies its loader, initrd and
# options and changes only the root subvolume.
cat >"$ESP/EFI/refind/aelum/$ID.conf" <<EOF
# Generated by the Aelum installer. Do not edit by hand.
# Root partition: /dev/vda2
menuentry "Aelum (vda2)" {
    icon /EFI/refind/themes/aelum/icons/os_arch.png
    loader /aelum/$ID/vmlinuz-linux-lts
    initrd /aelum/$ID/initramfs-linux-lts.img
    options "root=UUID=$UUID rw quiet quiet loglevel=3 rootflags=subvol=@"
}
EOF

cat >"$FAKE/etc/snapper/configs/root" <<EOF
SUBVOLUME="$FAKE/"
FSTYPE="btrfs"
EOF

info() { # num type date description
    mkdir -p "$FAKE/.snapshots/$1/snapshot"
    cat >"$FAKE/.snapshots/$1/info.xml" <<EOF
<?xml version="1.0"?>
<snapshot>
  <type>$2</type>
  <num>$1</num>
  <date>$3</date>
  <description>$4</description>
</snapshot>
EOF
}

# The shapes the menu has to label differently: a pacman pair, a pair a person
# named, a description outside ASCII, and a snapshot with nothing said about it.
info 1 single "2026-10-27 00:21:58" "setup quota test"
info 2 pre    "2026-10-27 09:00:00" "pacman"
info 3 post   "2026-10-27 09:04:00" "pacman"
info 4 pre    "2026-10-27 11:00:00" "Before I changed the GPU driver"
info 5 post   "2026-10-27 11:04:00" "Before I changed the GPU driver"
info 6 single "2026-10-27 12:00:00" "rentrée à vérifier"
info 10 single "2026-10-28 01:00:00" ""
mkdir -p "$FAKE/.snapshots/11"              # no snapshot/ dir: not a snapshot
echo "not a snapshot" >"$FAKE/.snapshots/notes"

# The snapper config path is the one absolute path in the generator. Rewriting
# it is what keeps the whole fixture under $FAKE; if the source stops matching,
# say so instead of testing against the host's own snapper config.
sed "s|\"/etc/snapper/configs/\$SNAPPER_CONFIG\"|\"$FAKE/etc/snapper/configs/\$SNAPPER_CONFIG\"|" \
    "$GEN" >"$FAKE/gen.sh"
if cmp -s "$GEN" "$FAKE/gen.sh"; then
    echo "the generator no longer reads /etc/snapper/configs/\$SNAPPER_CONFIG;" >&2
    echo "update this fixture before trusting its result." >&2
    exit 1
fi

run() { PATH="$BIN:$PATH" sh "$FAKE/gen.sh" >"$FAKE/run.out" 2>"$FAKE/run.err"; echo $?; }

echo "== one entry, every snapshot inside it =="
code=$(run)
[ "$code" = 0 ] && ok "generator exits 0" || bad "generator exited $code: $(cat "$FAKE/run.err")"
check "fragment written at $FRAGMENT" test -f "$FRAGMENT"
entries=$(count '^[[:space:]]*menuentry ' "$FRAGMENT")
submenus=$(count '^[[:space:]]*submenuentry ' "$FRAGMENT")
[ "$entries" = 1 ] && ok "exactly one menuentry (got $entries)" || bad "menuentry count is $entries, want 1"
[ "$submenus" = 7 ] && ok "all seven fixture snapshots listed (got $submenus)" ||
    bad "submenuentry count is $submenus, want 7"
check "the entry boots the newest snapshot taken before a change" \
    grep -qE '^# snapshot 4 pre$' "$FRAGMENT"
check "a pacman pair is labelled by what it is" grep -q 'Before system update' "$FRAGMENT"
check "a post snapshot is labelled as one" grep -q 'After system update' "$FRAGMENT"
check "a description written by a person is shown verbatim" \
    grep -q 'Before I changed the GPU driver' "$FRAGMENT"
check "the date survives being labelled" grep -qE '27 Oct 2026 11:00' "$FRAGMENT"
check "a description outside ASCII keeps only what the menu font can draw" \
    grep -qE 'submenuentry "Snapshot 6 - [^"]+ - 27 Oct 2026 12:00"' "$FRAGMENT"
absent "no bytes rEFInd's font cannot draw anywhere in the fragment" '[^ -~]' "$FRAGMENT"
check "a snapshot with no description is still named and dated" \
    grep -qE 'submenuentry "Snapshot 10 - 28 Oct 2026 01:00"' "$FRAGMENT"
absent "a directory that is not a snapshot is not listed" 'Snapshot 11|Snapshot notes' "$FRAGMENT"
check "only the root subvolume is swapped for the snapshot" \
    grep -q 'options "root=UUID=3f5b5703-93af-49ca-8fbb-9d93703a72c8 rw quiet quiet loglevel=3 rootflags=subvol=@/.snapshots/4/snapshot"' "$FRAGMENT"
check "the entry and every submenuentry each name one snapshot root" \
    bash -c '[ "$(grep -c "rootflags=subvol=@/.snapshots/" "$1")" = 8 ]' _ "$FRAGMENT"

echo "== running it twice changes nothing =="
cp "$FRAGMENT" "$FAKE/first.conf"
code=$(run)
check "the fragment is identical" cmp -s "$FAKE/first.conf" "$FRAGMENT"

echo "== a snapshot is deleted =="
rm -rf "$FAKE/.snapshots/10"
code=$(run)
submenus=$(count '^[[:space:]]*submenuentry ' "$FRAGMENT")
[ "$submenus" = 6 ] && ok "one fewer submenuentry (got $submenus)" || bad "submenuentry count is $submenus, want 6"

echo "== no snapshots at all =="
rm -rf "$FAKE/.snapshots"
code=$(run)
[ "$code" = 0 ] && ok "generator exits 0 with nothing to show" || bad "generator exited $code"
entries=$(count '^[[:space:]]*menuentry ' "$FRAGMENT")
[ "$entries" = 0 ] && ok "no entry written (an icon that boots nothing is worse than none)" ||
    bad "menuentry count is $entries, want 0"

echo "== the ESP is gone =="
rm -rf "$ESP"
code=$(run)
[ "$code" != 0 ] && ok "generator fails when it cannot write a menu" || bad "generator exited 0 with no ESP"
check "it says why" grep -qi 'no mounted ESP' "$FAKE/run.err"

echo
if [ "$fails" = 0 ]; then
    echo "all checks passed"
    [ "$KEEP" = 1 ] && echo "fixture kept: $FAKE"
    exit 0
fi
echo "$fails check(s) failed"
[ "$KEEP" = 1 ] && echo "fixture kept: $FAKE"
exit 1
