#!/usr/bin/env bash
set -uo pipefail

# fake-snapshot-menu.sh — run the boot-menu generator against a fixture, on the
# host, with no disk and no root.
#
#   ./scripts/fake-snapshot-menu.sh          # extract the generator and run it
#   GEN=/tmp/gen.sh ./scripts/fake-snapshot-menu.sh   # run a script you already have
#
# What exists here is a fake ESP (with this install's own menu entry to copy
# options from), a fake snapper config, a fake snapshot store, and a stub
# findmnt that answers the three questions the generator asks. Everything it
# reads and writes is under one temporary directory.
#
# This is not the installer's test suite: those check the text of the generator.
# This one runs it as shell, which is the only way to catch a fragment that is
# malformed, a title that lost its date, or a run that leaves the file behind
# when the snapshots are gone. It does not touch the real mount table, and it
# says so: a real boot is checked by make -C docker test-one / menu-shots.
#
# The generator is run the way the installer runs it - with --root at the tree it
# is writing about - which is what keeps every path in this fixture under $FAKE.
#
# Each section starts by rebuilding the snapshot tree (reset_snapshots), because
# "what the menu looks like after X" is only checkable when the tree before X is
# known.

PROFILE_DIR="$(cd "$(dirname "$0")/.." && pwd)"
GEN="${GEN:-$PROFILE_DIR/logs/snapshot-menu/aelum-refind-snapshots.sh}"
KEEP="${KEEP:-0}"

fails=0
ok()   { echo "  ok   - $*"; }
bad()  { echo "  FAIL - $*"; fails=$((fails + 1)); }
check() { # check <description> <command...>
    local desc=$1; shift
    if "$@" >/dev/null 2>&1; then ok "$desc"; else bad "$desc  [$*]"; fi
}
absent() { # absent <description> <pattern> <file>
    local desc=$1 pat=$2 file=$3
    if LC_ALL=C grep -qE "$pat" "$file" 2>/dev/null; then bad "$desc"; else ok "$desc"; fi
}
count() { local n; n=$(grep -cE "$1" "$2" 2>/dev/null); echo "${n:-0}"; }
# want_count <expected> <pattern> <file> <what it counts>
want_count() {
    local want=$1 pat=$2 file=$3 what=$4 got
    got=$(count "$pat" "$file")
    if [ "$got" = "$want" ]; then ok "$what is $got"; else bad "$what is $got, want $want"; fi
}

if [ ! -x "$GEN" ]; then
    echo "extracting the generator from the installer source ..."
    OUT="$GEN" "$PROFILE_DIR/scripts/extract-snapshot-generator.sh" || exit 1
fi
[ -r "$GEN" ] || { echo "no generator to run: $GEN" >&2; exit 1; }

FAKE=$(mktemp -d /tmp/aelum-fake-snapshot-menu.XXXXXX)
[ "$KEEP" = 1 ] || trap 'rm -rf "$FAKE"' EXIT
BIN="$FAKE/bin"
ID=3f5b5703
UUID=3f5b5703-93af-49ca-8fbb-9d93703a72c8
ESP="$FAKE/efi"
FRAGMENT="$ESP/EFI/refind/aelum/$ID-snapshots.conf"
SNAPS="$FAKE/.snapshots"

mkdir -p "$BIN" "$ESP/EFI/refind/aelum" "$FAKE/etc/snapper/configs"

# Stub findmnt: the lookups the generator makes, in the spelling the real findmnt
# uses (a btrfs subvolume mount is reported as /dev/vda2[/@/.snapshots]).
cat >"$BIN/findmnt" <<EOF
#!/bin/sh
case "\$*" in
    *"TARGET -t vfat"*) echo "$ESP" ;;
    *"no UUID"*)        echo "$UUID" ;;
    *"no SOURCE"*)      echo "/dev/vda2[/@/.snapshots]" ;;
    *)                 exit 0 ;;
esac
EOF
chmod +x "$BIN/findmnt"

# Stub btrfs: the generator asks one question of btrfs - which subvolume the
# filesystem treats as the system. That is what a rollback moves, and the path of
# the history is derived from it. The fixture's default is the snapshot the
# installer installs into, which is what a real Aelum install reports.
cat >"$BIN/btrfs" <<EOF
#!/bin/sh
case "\$*" in
    *"subvolume get-default"*) echo "ID 266 gen 1 top level 258 path @/.snapshots/1/snapshot" ;;
    *)                        exit 0 ;;
esac
EOF
chmod +x "$BIN/btrfs"

# This install's own menu entry: the generator copies its loader, initrd and
# options and adds only the root subvolume. The installer's entry names none - the
# boot follows the default subvolume the stub above reports.
cat >"$ESP/EFI/refind/aelum/$ID.conf" <<EOF
# Generated by the Aelum installer. Do not edit by hand.
# Root partition: /dev/vda2
menuentry "Aelum (vda2)" {
    icon /EFI/refind/themes/aelum/icons/os_arch.png
    loader /aelum/$ID/vmlinuz-linux-lts
    initrd /aelum/$ID/initramfs-linux-lts.img
    options "root=UUID=$UUID rw quiet quiet loglevel=3"
}
EOF

cat >"$FAKE/etc/snapper/configs/root" <<EOF
SUBVOLUME="/"
FSTYPE="btrfs"
EOF

# info <num> <type> <date> <description> [cleanup] [important]
#
# The optional fifth and sixth arguments are the two things snapper records about
# a snapshot that the menu needs and a directory listing does not say: which
# cleanup algorithm owns it ("timeline" is the automatic history) and whether it
# is marked important. An info.xml without them is what `snapper create` writes.
#
# Userdata is written the way snapper writes it (measured on a real install's
# "after installation" snapshot): a list of <key>/<value> pairs. Prefix the value
# with "flat:" for the flat <important>yes</important> spelling, which the
# generator also accepts.
info() { # num type date description [cleanup] [important]
    local num=$1 type=$2 date=$3 desc=$4 cleanup=${5:-} important=${6:-}
    mkdir -p "$SNAPS/$num/snapshot"
    {
        echo '<?xml version="1.0"?>'
        echo '<snapshot>'
        echo "  <type>$type</type>"
        echo "  <num>$num</num>"
        echo "  <date>$date</date>"
        echo "  <description>$desc</description>"
        [ -n "$cleanup" ] && echo "  <cleanup>$cleanup</cleanup>"
        if [ -n "$important" ]; then
            case "$important" in
                flat:*) echo '  <important>yes</important>' ;;
                *)
                    echo '  <userdata>'
                    echo '    <key>important</key>'
                    echo "    <value>$important</value>"
                    echo '  </userdata>'
                    ;;
            esac
        fi
        echo '</snapshot>'
    } >"$SNAPS/$num/info.xml"
}

# reset_snapshots rebuilds the tree every section starts from.
#
# The shapes the menu has to handle, and the numbers are the ones a real install
# has: #1 is the snapshot the system was installed into (the default subvolume,
# so not offered), #2/#3 and #4/#5 are pre/post pairs, #6 has a description
# outside ASCII, #8 has one containing the generator's own field separator, #10
# says nothing at all. #11 is a directory that is not a snapshot.
reset_snapshots() {
    rm -rf "$SNAPS"
    mkdir -p "$SNAPS/11"
    echo "not a snapshot" >"$SNAPS/notes"
    info 1 single "2026-10-27 00:21:58" "first root filesystem" number
    info 2 pre    "2026-10-27 09:00:00" "pacman" number
    info 3 post   "2026-10-27 09:04:00" "pacman" number
    info 4 pre    "2026-10-27 11:00:00" "Before I changed the GPU driver" number
    info 5 post   "2026-10-27 11:04:00" "Before I changed the GPU driver" number
    info 6 single "2026-10-27 12:00:00" "rentrée à vérifier"
    info 8 single "2026-10-27 13:00:00" "before | after"
    info 10 single "2026-10-28 01:00:00" ""
}
reset_snapshots

# timeline <num> <date> — a snapshot of the kind snapper-timeline.timer creates.
timeline() { # num date
    info "$1" single "$2" "" timeline
}

# The generator is run with --root at this fixture, exactly as the installer runs
# it against the system being installed. Every path it resolves - the ESP, the
# snapper config, the history - is under $FAKE, and the stubs above answer the
# two questions that are not plain paths.
run() { PATH="$BIN:$PATH" sh "$GEN" --root "$FAKE" >"$FAKE/run.out" 2>"$FAKE/run.err"; echo $?; }
run_root() { PATH="$BIN:$PATH" sh "$GEN" --root "$1" >"$FAKE/run.out" 2>"$FAKE/run.err"; echo $?; }
run_path() { PATH="$1" sh "$GEN" --root "$FAKE" >"$FAKE/run.out" 2>"$FAKE/run.err"; echo $?; }

# entry_target — the number of the snapshot the menuentry itself boots, read back
# from the "# snapshot <n> <type>" comment the generator writes above it.
entry_target() { sed -n 's/^# snapshot \([0-9]*\) .*/\1/p' "$FRAGMENT" | head -n1; }

echo "== one entry, every snapshot inside it =="
code=$(run)
[ "$code" = 0 ] && ok "generator exits 0 (got $code)" || bad "generator exited $code: $(cat "$FAKE/run.err")"
check "fragment written at $FRAGMENT" test -f "$FRAGMENT"
want_count 1 '^[[:space:]]*menuentry ' "$FRAGMENT" "menuentry count"
want_count 7 '^[[:space:]]*submenuentry ' "$FRAGMENT" "submenuentry count"
[ "$(entry_target)" = 4 ] && ok "the entry boots the newest snapshot taken before a change (got $(entry_target))" ||
    bad "entry target is $(entry_target), want 4"
check "a pacman pair is labelled by what it is" grep -q 'Before system update' "$FRAGMENT"
check "a post snapshot is labelled as one" grep -q 'After system update' "$FRAGMENT"
check "a description written by a person is shown verbatim" \
    grep -q 'Before I changed the GPU driver' "$FRAGMENT"
check "the date survives being labelled" grep -qE '27 Oct 2026 11:00' "$FRAGMENT"
check "a description outside ASCII keeps only what the menu font can draw" \
    grep -qE 'submenuentry "Snapshot 6 - [^"]+ - 27 Oct 2026 12:00"' "$FRAGMENT"
absent "no bytes rEFInd's font cannot draw anywhere in the fragment" '[^ -~]' "$FRAGMENT"
check "a snapshot with no description is still named and dated" \
    grep -qE 'submenuentry "Snapshot 10 - 28 Oct 2026 01:00"' "$FRAGMENT"
absent "a directory that is not a snapshot is not listed" 'Snapshot 11|Snapshot notes' "$FRAGMENT"
check "only the root subvolume is swapped for the snapshot" \
    grep -q 'options "root=UUID=3f5b5703-93af-49ca-8fbb-9d93703a72c8 rw quiet quiet loglevel=3 rootflags=subvol=@/.snapshots/4/snapshot"' "$FRAGMENT"
check "the entry and every submenuentry each name one snapshot root" \
    bash -c '[ "$(grep -c "rootflags=subvol=@/.snapshots/" "$1")" = 8 ]' _ "$FRAGMENT"
absent "the entry this install boots is never rewritten by the generator" 'menuentry "Aelum \(vda2\)"' "$FRAGMENT"
# A '|' inside a description would otherwise end the generator's own field and
# shift everything after it: the title is the field, so the pipe cannot be in it.
check "a description containing the field separator keeps its title and its date" \
    grep -qE 'submenuentry "Snapshot 8 - before after - 27 Oct 2026 13:00"' "$FRAGMENT"

echo "== the snapshot that is the system is not offered =="
# #1 is the default subvolume: this install's own entry boots it (it names no
# subvolume, so it follows that pointer) and a rollback moves it. Offering it as a
# state to go back to would offer the user the state they are already in.
absent "the default subvolume's snapshot is not in the submenu" 'Snapshot 1 -' "$FRAGMENT"
absent "no entry names the default subvolume's snapshot" 'rootflags=subvol=@/\.snapshots/1/snapshot' "$FRAGMENT"
rm -rf "$SNAPS/2" "$SNAPS/3" "$SNAPS/4" "$SNAPS/5" "$SNAPS/6" "$SNAPS/8" "$SNAPS/10" "$SNAPS/11"
code=$(run)
[ "$code" = 0 ] && ok "generator exits 0 with only the system itself to show" || bad "generator exited $code"
want_count 0 '^[[:space:]]*menuentry ' "$FRAGMENT" "menuentry count with only the default snapshot"
reset_snapshots
run >/dev/null

echo "== running it twice changes nothing =="
cp "$FRAGMENT" "$FAKE/first.conf"
code=$(run)
check "the fragment is identical" cmp -s "$FAKE/first.conf" "$FRAGMENT"

echo "== --root with a trailing slash =="
# The installed system's own run passes no --root at all, which is the same shape
# as asking for the fixture with a slash on the end: both end in a root that must
# not be reduced to an empty string.
cp "$FRAGMENT" "$FAKE/before-slash.conf"
code=$(run_root "$FAKE/")
[ "$code" = 0 ] && ok "generator exits 0 (got $code)" || bad "generator exited $code: $(cat "$FAKE/run.err")"
check "the fragment is identical with a trailing slash" cmp -s "$FAKE/before-slash.conf" "$FRAGMENT"
check "every entry still names a subvolume that exists in the fixture" \
    bash -c '[ "$(grep -c "rootflags=subvol=@/.snapshots/" "$1")" = 8 ]' _ "$FRAGMENT"

echo "== btrfs cannot name the default subvolume =="
# Without the default subvolume there is no correct path to name a snapshot by.
# Writing stanzas anyway produced rootflags=subvol=.snapshots/N/snapshot - a path
# that is not in the filesystem tree, so the entry could not mount a root.
mkdir -p "$FAKE/bin-quiet"
cat >"$FAKE/bin-quiet/btrfs" <<'STUB'
#!/bin/sh
exit 0
STUB
chmod +x "$FAKE/bin-quiet/btrfs"
cp "$FRAGMENT" "$FAKE/before-quiet.conf"
code=$(run_path "$FAKE/bin-quiet:$BIN:$PATH")
[ "$code" = 0 ] && ok "generator exits 0 rather than guessing" || bad "generator exited $code"
check "the menu already on the ESP is left exactly as it is" cmp -s "$FAKE/before-quiet.conf" "$FRAGMENT"
check "it says why" grep -qi 'cannot read the default subvolume' "$FAKE/run.err"

echo "== a default subvolume that is not a snapshot =="
# A layout someone reset with btrfs subvolume set-default @: the history path is
# still derived from it, and now every numbered snapshot is a state to go back
# to - including #1, which is no longer the system.
mkdir -p "$FAKE/bin-plain"
cat >"$FAKE/bin-plain/btrfs" <<'STUB'
#!/bin/sh
case "$*" in
    *"subvolume get-default"*) echo "ID 258 gen 1 top level 5 path @" ;;
    *)                        exit 0 ;;
esac
STUB
chmod +x "$FAKE/bin-plain/btrfs"
code=$(run_path "$FAKE/bin-plain:$BIN:$PATH")
[ "$code" = 0 ] && ok "generator exits 0 (got $code)" || bad "generator exited $code: $(cat "$FAKE/run.err")"
want_count 8 '^[[:space:]]*submenuentry ' "$FRAGMENT" "submenuentry count when the default is a plain subvolume"
check "the history is still named from the default subvolume" \
    grep -q 'rootflags=subvol=@/\.snapshots/' "$FRAGMENT"
check "the old system snapshot is offered again" grep -qE 'submenuentry "Snapshot 1 - first root filesystem' "$FRAGMENT"
reset_snapshots
code=$(run)

echo "== timeline snapshots are listed, never booted as the entry =="
# snapper-timeline.timer takes a snapshot on a schedule. It is the "when did this
# break?" history, so it belongs in the submenu - but a timer that fired at 03:00
# is not a state anyone chose to return to, and it must not become the recovery
# entry the icon boots.
timeline 20 "2026-10-29 03:00:00"
code=$(run)
[ "$(entry_target)" = 4 ] && ok "the newest timeline snapshot did not take the entry (target $(entry_target))" ||
    bad "entry target is $(entry_target), want 4 (the newest pre snapshot)"
check "the timeline snapshot is still listed in the submenu" \
    grep -qE 'submenuentry "Snapshot 20 - 29 Oct 2026 03:00"' "$FRAGMENT"

echo "== the states worth keeping are not crowded out =="
# A dozen timeline snapshots is what snapper keeps, and a plain newest-N list is
# all of them and no decisions. The states a transaction or a person created are
# collected first, and the automatic history fills whatever room is left.
n=30
while [ "$n" -le 39 ]; do timeline "$n" "2026-10-29 $(printf '%02d' "$((n - 30))"):00:00"; n=$((n + 1)); done
code=$(run)
[ "$(entry_target)" = 4 ] && ok "ten newer timeline snapshots did not take the entry (target $(entry_target))" ||
    bad "entry target is $(entry_target), want 4"
check "the pre snapshot is still listed after a dozen timestamps" \
    grep -qE 'submenuentry "Snapshot 4 - Before I changed the GPU driver' "$FRAGMENT"
check "the post snapshot is still listed too" \
    grep -qE 'submenuentry "Snapshot 5 - Before I changed the GPU driver' "$FRAGMENT"
want_count 8 '^[[:space:]]*submenuentry ' "$FRAGMENT" "submenuentry count (the bounded list stays bounded)"

echo "== with no pre snapshot the entry is the important one =="
# The second rung: a rollback backup, or the "after installation" state of a
# system that has not been updated yet. important=yes is snapper's own marker, and
# it outranks a newer snapshot nobody chose.
reset_snapshots
rm -rf "$SNAPS/2" "$SNAPS/4"
info 7 single "2026-10-27 14:00:00" "factory restore point" number yes
timeline 21 "2026-10-29 04:00:00"
code=$(run)
[ "$(entry_target)" = 7 ] && ok "the entry is the snapshot marked important (target $(entry_target))" ||
    bad "entry target is $(entry_target), want 7 (the newest important snapshot)"
check "the entry is titled with what it is" \
    grep -q 'menuentry "Aelum snapshot 7 - factory restore point (27 Oct 2026 14:00)"' "$FRAGMENT"
absent "the newer timeline snapshot is not the entry" 'menuentry "Aelum snapshot 21' "$FRAGMENT"
reset_snapshots

echo "== userdata spelled the flat way =="
# The generator reads snapper's real <key>/<value> pair. It also accepts the flat
# <important>yes</important> spelling rather than treating a snapshot it cannot
# read as one nobody marked.
reset_snapshots
rm -rf "$SNAPS/2" "$SNAPS/4"
info 7 single "2026-10-27 14:00:00" "factory restore point" number flat:yes
code=$(run)
[ "$(entry_target)" = 7 ] && ok "the flat spelling is still the important snapshot (target $(entry_target))" ||
    bad "entry target is $(entry_target), want 7"
reset_snapshots

echo "== a snapshot is deleted =="
reset_snapshots
rm -rf "$SNAPS/10"
code=$(run)
want_count 6 '^[[:space:]]*submenuentry ' "$FRAGMENT" "submenuentry count after deleting one"

echo "== no snapshots at all =="
rm -rf "$SNAPS"
code=$(run)
[ "$code" = 0 ] && ok "generator exits 0 with nothing to show" || bad "generator exited $code"
want_count 0 '^[[:space:]]*menuentry ' "$FRAGMENT" "menuentry count (an icon that boots nothing is worse than none)"

echo "== the ESP is gone =="
rm -rf "$ESP"
code=$(run)
[ "$code" != 0 ] && ok "generator fails when it cannot write a menu" || bad "generator exited 0 with no ESP"
check "it says why" grep -qi 'no mounted ESP' "$FAKE/run.err"

echo
if [ "$fails" = 0 ]; then
    echo "all checks passed"
    [ "$KEEP" = 1 ] && echo "fixture kept: $FAKE"
    exit 0
fi
echo "$fails check(s) failed"
[ "$KEEP" = 1 ] && echo "fixture kept: $FAKE"
exit 1
